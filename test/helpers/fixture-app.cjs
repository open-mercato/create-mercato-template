// Shared fixture builder (spec Step 3). It writes a minimal valid Open
// Mercato app: a package.json that depends on @open-mercato/core with
// packageManager yarn@4.x, a minimal Yarn 4 yarn.lock that resolves it,
// src/modules.ts and .env.example. Every later fixture derives from it, so the
// root rules of Step 4 do not turn the fixtures into errors. It also has a
// README.md (Step 8), so the readme-missing warning does not show up in
// every report.
//
// Git runs against repositories in a temp directory, with an isolated
// configuration (no user or system config, no hooks, a fixed identity and
// date), so the fixtures are byte-identical everywhere. No network.
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { spawnSync } = require('node:child_process')

const coreVersion = '0.9.0'

const packageJson = {
  name: 'fixture-app',
  version: '0.1.0',
  private: true,
  description: 'A minimal Open Mercato app used by the create-mercato-template tests.',
  packageManager: 'yarn@4.12.0',
  engines: { node: '>=24' },
  dependencies: { '@open-mercato/core': coreVersion },
}

const yarnLock = `# This file is generated by running "yarn install" inside your project.
# Manual changes might be lost - proceed with caution!

__metadata:
  version: 8
  cacheKey: 10c0

"@open-mercato/core@npm:${coreVersion}":
  version: ${coreVersion}
  resolution: "@open-mercato/core@npm:${coreVersion}"
  checksum: 10c0/${'0'.repeat(128)}
  languageName: node
  linkType: hard

"fixture-app@workspace:.":
  version: 0.0.0-use.local
  resolution: "fixture-app@workspace:."
  dependencies:
    "@open-mercato/core": "npm:${coreVersion}"
  languageName: unknown
  linkType: soft
`

const modulesTs = `export type ModuleEntry = { id: string; from?: '@open-mercato/core' | '@app' | string }

export const enabledModules: ModuleEntry[] = [
  { id: 'auth', from: '@open-mercato/core' },
  { id: 'directory', from: '@open-mercato/core' },
]
`

const envExample = `# Public URL of the app.
APP_URL=http://localhost:3000
`

const readme = `# Fixture app

A minimal Open Mercato app used by the create-mercato-template tests.
`

/** The files of the minimal app, by repo-relative path. */
const fixtureFiles = Object.freeze({
  '.gitignore': 'node_modules/\n.env\n',
  'README.md': readme,
  'package.json': `${JSON.stringify(packageJson, null, 2)}\n`,
  'yarn.lock': yarnLock,
  'src/modules.ts': modulesTs,
  '.env.example': envExample,
})

/** A Git environment that ignores the user's and the system's configuration. */
function gitEnvironment(extra = {}) {
  const environment = { ...process.env }
  for (const name of Object.keys(environment)) if (name.startsWith('GIT_')) delete environment[name]
  return {
    ...environment,
    GIT_CONFIG_GLOBAL: '/dev/null',
    GIT_CONFIG_NOSYSTEM: '1',
    GIT_AUTHOR_NAME: 'Fixture',
    GIT_AUTHOR_EMAIL: 'fixture@example.com',
    GIT_AUTHOR_DATE: '2026-11-03T12:00:00Z',
    GIT_COMMITTER_NAME: 'Fixture',
    GIT_COMMITTER_EMAIL: 'fixture@example.com',
    GIT_COMMITTER_DATE: '2026-11-03T12:00:00Z',
    ...extra,
  }
}

/** Runs Git in `cwd` with the isolated environment; throws on failure. Returns stdout as a Buffer. */
function git(cwd, args, input) {
  const result = spawnSync('git', ['-c', 'core.hooksPath=/dev/null', '-c', 'commit.gpgsign=false', ...args], {
    cwd,
    env: gitEnvironment(),
    input,
  })
  if (result.error) throw result.error
  if (result.status !== 0) throw new Error(`git ${args.join(' ')} failed: ${result.stderr.toString()}`)
  return result.stdout
}

/** A new empty temp directory, real path (macOS /tmp is a symlink). */
function tempDir(prefix = 'cmt-') {
  return fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), prefix)))
}

/**
 * Writes files under `root`. `files` maps repo-relative paths to contents
 * (string or Buffer); `null` skips a path of the base set. With `base`
 * (default true) the minimal app comes first.
 */
function writeFixtureApp(root, files = {}, { base = true } = {}) {
  const all = { ...(base ? fixtureFiles : {}), ...files }
  for (const [relative, content] of Object.entries(all)) {
    if (content === null) continue
    const target = path.join(root, ...relative.split('/'))
    fs.mkdirSync(path.dirname(target), { recursive: true })
    fs.writeFileSync(target, content)
  }
  return root
}

/**
 * A Git repository in a new temp directory holding the fixture app (plus
 * `files`), with every file committed. Returns its real path.
 */
function createFixtureRepo(files = {}, { base = true, commit = true } = {}) {
  const root = tempDir('cmt-app-')
  git(root, ['init', '-q', '-b', 'main', '--template='])
  writeFixtureApp(root, files, { base })
  if (commit) {
    git(root, ['add', '-A'])
    git(root, ['commit', '-q', '-m', 'Fixture app'])
  }
  return root
}

/**
 * Adds index entries with plumbing and commits them, for entries a file
 * system cannot hold portably: a path with a tab, a path that is not valid
 * UTF-8, two paths that differ only in case, a symlink, a gitlink. Each entry
 * is `{ path: string | Buffer, mode?: '100644' | '120000' | '160000', content?: string | Buffer, oid?: string }`.
 * The worktree is left as it was.
 */
function commitIndexEntries(root, entries, message = 'Plumbing entries') {
  const records = entries.map((entry) => {
    const mode = entry.mode ?? '100644'
    const oid = entry.oid ?? git(root, ['hash-object', '-w', '--stdin'], Buffer.from(entry.content ?? '')).toString().trim()
    const name = Buffer.isBuffer(entry.path) ? entry.path : Buffer.from(entry.path, 'utf8')
    return Buffer.concat([Buffer.from(`${mode} ${oid}\t`), name, Buffer.of(0)])
  })
  git(root, ['update-index', '-z', '--index-info'], Buffer.concat(records))
  git(root, ['commit', '-q', '-m', message])
}

module.exports = {
  coreVersion,
  fixtureFiles,
  gitEnvironment,
  git,
  tempDir,
  writeFixtureApp,
  createFixtureRepo,
  commitIndexEntries,
}
